package cn.tolim.pudans.core.ai.memory.asset;

import cn.tolim.pudans.contract.ai.resource.AiMemoryAsset;
import java.util.List;

public record MemoryAssetView(
        String name,
        String displayName,
        String description,
        String team,
        String ownerUserId,
        String sourceUserId,
        String sourceAgentId,
        AiMemoryAsset.Visibility visibility,
        AiMemoryAsset.Status status,
        boolean autoGenerated,
        List<String> agents,
        String createdByUserId,
        MemoryLayerCounts counts) {

    public MemoryAssetView {
        agents = agents == null ? List.of() : List.copyOf(agents);
    }
}