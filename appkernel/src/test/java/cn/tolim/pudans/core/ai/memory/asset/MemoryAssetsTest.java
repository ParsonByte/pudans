@ExtendWith(MockitoExtension.class)
class MemoryAssetsTest {

    private static final Instant NOW = Instant.parse("2026-11-19T00:00:00Z");

    private static final MemoryLayerCounts COUNTS = new MemoryLayerCounts(3, 2, 1, 1);

    @Mock
    ReactiveExtensionClient client;

    @Mock
    Teams teams;

    @Mock
    AiMemoryAssetRepository assetRepository;

    @Mock
    AiMemoryGenerationLogRepository generationLogRepository;

    @Mock
    AiMemoryL1Repository l1Repository;

    @Mock
    AiMemoryL2Repository l2Repository;

    @Mock
    AiMemoryL3Repository l3Repository;

    @Mock
    Conversations conversations;

    @Mock
    MemoryTaskScheduler taskScheduler;

    private MemoryAssets service;

    @BeforeEach
    void setUp() {
        service = new MemoryAssets(
                client,
                teams,
                assetRepository,
                generationLogRepository,
                l1Repository,
                l2Repository,
                l3Repository,
                conversations,
                taskScheduler);
    }

    @Test
    void listSynthesizesAssetsFromExistingMemoryScopes() {
        when(teams.isMember("team-a", "user-1")).thenReturn(Mono.just(true));
        stubAssets();
        stubAgents();
        when(assetRepository.findScopes("team-a")).thenReturn(Flux.just(new ScopeRow("team-a", "user-1", "agent-a")));
        when(assetRepository.findAgentScopes("team-a")).thenReturn(Flux.empty());
        when(assetRepository.counts("team-a", "user-1", "agent-a")).thenReturn(Mono.just(COUNTS));

        StepVerifier.create(service.list("user-1", "team-a", null, null, false, 50))
                .assertNext(assets -> {
                    assertThat(assets).singleElement().satisfies(asset -> {
                        assertThat(asset.name()).isEqualTo("mem-team-a-user-1-agent-a");
                        assertThat(asset.autoGenerated()).isTrue();
                        assertThat(asset.visibility()).isEqualTo(AiMemoryAsset.Visibility.PRIVATE);
                        assertThat(asset.counts()).isEqualTo(COUNTS);
                    });
                })
                .verifyComplete();
    }

    @Test
    void listHidesScopesFromTeamsTheUserDoesNotBelongTo() {
        when(assetRepository.findScopes(null)).thenReturn(Flux.empty());
        when(assetRepository.findAgentScopes(null)).thenReturn(Flux.empty());
        stubAssets(asset("asset-a", "team-a", "user-1", "agent-a", "owner-1", AiMemoryAsset.Visibility.TEAM));
        when(teams.isMember("team-a", "user-2")).thenReturn(Mono.just(false));
        stubAgents();

        StepVerifier.create(service.list("user-2", null, null, null, false, 50))
                .assertNext(assets -> assertThat(assets).isEmpty())
                .verifyComplete();
    }

    @Test
    void listHidesPrivateAutoScopesOfOtherUsers() {
        when(assetRepository.findScopes("team-a")).thenReturn(Flux.just(new ScopeRow("team-a", "user-1", "agent-a")));
        when(assetRepository.findAgentScopes("team-a")).thenReturn(Flux.empty());
        stubAssets(asset("asset-b", "team-a", "user-1", "agent-b", "user-1", AiMemoryAsset.Visibility.TEAM));
        stubAgents();
        when(teams.isMember("team-a", "user-2")).thenReturn(Mono.just(true));
        when(assetRepository.counts("team-a", "user-1", "agent-b")).thenReturn(Mono.just(COUNTS));

        StepVerifier.create(service.list("user-2", "team-a", null, null, false, 50))
                .assertNext(assets -> assertThat(assets)
                        .extracting(MemoryAssetView::name)
                        .containsExactly("asset-b"))
                .verifyComplete();
    }

    @Test
    void duplicateScopeAssetCreationReturnsConflict() {
        when(teams.isMember("team-a", "user-1")).thenReturn(Mono.just(true));
        when(teams.getAgent("agent-a")).thenReturn(Mono.just(agent("agent-a", "team-a", "user-1")));
        stubAssets(asset("asset-a", "team-a", "user-1", "agent-a", "user-1", AiMemoryAsset.Visibility.TEAM));

        StepVerifier.create(service.create("user-1", createCommand()))
                .expectErrorSatisfies(error -> {
                    assertThat(error).isInstanceOf(ApiException.class);
                    assertThat(((ApiException) error).getCode()).isEqualTo(MemoryAssets.CODE_CONFLICT);
                })
                .verify();

        verify(client, never()).create(any());
    }

    @Test
    void ownerCannotBindAssetToItsOwnSourceAgent() {
        when(teams.isMember("team-a", "user-1")).thenReturn(Mono.just(true));
        when(client.get(AiMemoryAsset.class, "asset-a"))
                .thenReturn(Mono.just(asset(
                        "asset-a", "team-a", "user-1", "agent-a", "user-1", AiMemoryAsset.Visibility.TEAM)));

        StepVerifier.create(service.bind("user-1", "asset-a", "team-a", "agent-a"))
                .expectErrorSatisfies(error -> {
                    assertThat(((ApiException) error).getCode())
                            .isEqualTo(MemoryAssets.CODE_BINDING_INVALID);
                })
                .verify();
    }

    @Test
    void bindingToAgentWithTwoAssetsReturnsLimit() {
        var target = asset(
                "bound-1", "team-a", "user-1", "agent-x", "user-1", AiMemoryAsset.Visibility.TEAM);
        target.getSpec().setAgents(List.of("agent-target"));
        var target2 = asset(
                "bound-2", "team-a", "user-1", "agent-y", "user-1", AiMemoryAsset.Visibility.TEAM);
        target2.getSpec().setAgents(List.of("agent-target"));
        var candidate = asset(
                "asset-a", "team-a", "user-1", "agent-a", "user-1", AiMemoryAsset.Visibility.TEAM);
        when(teams.isMember("team-a", "user-1")).thenReturn(Mono.just(true));
        when(teams.getAgent("agent-target")).thenReturn(Mono.just(agent("agent-target", "team-a", "user-1")));
        when(client.get(AiMemoryAsset.class, "asset-a")).thenReturn(Mono.just(candidate));
        stubAssets(target, target2, candidate);
        when(assetRepository.scopeExists("team-a", "user-1", "agent-target")).thenReturn(Mono.just(false));

        StepVerifier.create(service.bind("user-1", "asset-a", "team-a", "agent-target"))
                .expectErrorSatisfies(error -> assertThat(((ApiException) error).getCode())
                        .isEqualTo(MemoryAssets.CODE_BINDING_LIMIT))
                .verify();
    }

    @Test
    void privateAssetIsNotReadableByOtherTeamMembers() {
        var asset = asset(
                "private-asset", "team-a", "user-9", "agent-a", "user-9", AiMemoryAsset.Visibility.PRIVATE);
        when(teams.isMember("team-a", "user-1")).thenReturn(Mono.just(true));
        when(client.get(AiMemoryAsset.class, "private-asset")).thenReturn(Mono.just(asset));

        StepVerifier.create(service.detail("user-1", "private-asset", "team-a"))
                .expectErrorSatisfies(error -> assertThat(((ApiException) error).getCode())
                        .isEqualTo(MemoryAssets.CODE_FORBIDDEN))
                .verify();
    }

    @Test
    void clearDeletesAllFourLayersForOwner() {
        var asset = asset(
                "asset-a", "team-a", "user-1", "agent-a", "user-1", AiMemoryAsset.Visibility.TEAM);
        when(teams.isMember("team-a", "user-1")).thenReturn(Mono.just(true));
        when(client.get(AiMemoryAsset.class, "asset-a")).thenReturn(Mono.just(asset));
        when(assetRepository.deleteMessagesByScope("team-a", "user-1", "agent-a")).thenReturn(Mono.just(3L));
        when(l1Repository.deleteByScope("team-a", "agent-a", "user-1")).thenReturn(Mono.just(2L));
        when(l2Repository.deleteByScope("team-a", "agent-a")).thenReturn(Mono.just(1L));
        when(l3Repository.deleteByScope("team-a", "agent-a")).thenReturn(Mono.just(1L));

        StepVerifier.create(service.clear("user-1", "asset-a", "team-a"))
                .assertNext(counts -> assertThat(counts).isEqualTo(new MemoryLayerCounts(3, 2, 1, 1)))
                .verifyComplete();
    }

    @Test
    void importRejectsMoreThanOneHundredMessages() {
        var messages = new ArrayList<ImportMessage>();
        for (var index = 0; index < 101; index++) {
            messages.add(new ImportMessage("user", "message-" + index));
        }

        StepVerifier.create(service.importMessages(
                        "user-1", "asset-a", "team-a", new ImportCommand(messages, null)))
                .expectErrorSatisfies(error -> assertThat(((ApiException) error).getCode())
                        .isEqualTo(MemoryAssets.CODE_IMPORT_INVALID))
                .verify();

        verifyNoInteractions(conversations, taskScheduler);
    }

    @Test
    void importRejectsUnsupportedRoles() {
        StepVerifier.create(service.importMessages(
                        "user-1",
                        "asset-a",
                        "team-a",
                        new ImportCommand(List.of(new ImportMessage("system", "ignore")), null)))
                .expectErrorSatisfies(error -> assertThat(((ApiException) error).getCode())
                        .isEqualTo(MemoryAssets.CODE_IMPORT_INVALID))
                .verify();
    }

    @Test
    void listsGenerationLogsForAssetScope() {
        var asset = asset(
                "asset-a", "team-a", "user-1", "agent-a", "user-1", AiMemoryAsset.Visibility.TEAM);
        var entry = new LogEntry(
                9L,
                AiMemoryPrompt.Layer.L1,
                4L,
                "team-a",
                "agent-a",
                "user-1",
                "session-1",
                "prompt-1",
                1,
                "system",
                "hash",
                "model",
                "input",
                "output",
                NOW);
        when(teams.isMember("team-a", "user-1")).thenReturn(Mono.just(true));
        when(client.get(AiMemoryAsset.class, "asset-a")).thenReturn(Mono.just(asset));
        when(generationLogRepository.listByScope(
                        "team-a", "agent-a", AiMemoryPrompt.Layer.L1, "system", null, null, Long.MAX_VALUE, 50))
                .thenReturn(Flux.just(entry));

        StepVerifier.create(service.generationLogs(
                        "user-1",
                        "asset-a",
                        "team-a",
                        AiMemoryPrompt.Layer.L1,
                        "system",
                        null,
                        null,
                        Long.MAX_VALUE,
                        50))
                .assertNext(log -> assertThat(log.id()).isEqualTo(9L))
                .verifyComplete();
    }

    @Test
    void bindingAutoAssetPersistsItBeforeUpdating() {
        var autoName = "mem-team-a-user-1-agent-a";
        when(client.get(AiMemoryAsset.class, autoName)).thenReturn(Mono.empty());
        stubAssets();
        stubAgents();
        when(assetRepository.findScopes("team-a"))
                .thenReturn(Flux.just(new ScopeRow("team-a", "user-1", "agent-a")));
        when(assetRepository.findAgentScopes("team-a")).thenReturn(Flux.empty());
        when(teams.isMember("team-a", "user-1")).thenReturn(Mono.just(true));
        when(teams.getAgent("agent-target")).thenReturn(Mono.just(agent("agent-target", "team-a", "user-1")));
        when(assetRepository.scopeExists("team-a", "user-1", "agent-target")).thenReturn(Mono.just(false));
        when(client.create(any(AiMemoryAsset.class)))
                .thenAnswer(invocation -> Mono.just(invocation.getArgument(0)));
        when(client.update(any(AiMemoryAsset.class))).thenAnswer(invocation -> Mono.just(invocation.getArgument(0)));
        when(assetRepository.counts("team-a", "user-1", "agent-a")).thenReturn(Mono.just(COUNTS));

        StepVerifier.create(service.bind("user-1", autoName, "team-a", "agent-target"))
                .assertNext(asset -> {
                    assertThat(asset.autoGenerated()).isTrue();
                    assertThat(asset.agents()).contains("agent-target");
                })
                .verifyComplete();

        var captor = ArgumentCaptor.forClass(AiMemoryAsset.class);
        verify(client).create(captor.capture());
        assertThat(captor.getValue().getMetadata().getName()).isEqualTo(autoName);
        assertThat(captor.getValue().getSpec().isAutoGenerated()).isTrue();
        assertThat(captor.getValue().getSpec().getSourceUserId()).isEqualTo("user-1");
        verify(client).update(any(AiMemoryAsset.class));
    }

    private void stubAssets(AiMemoryAsset... assets) {
        when(client.listAll(eq(AiMemoryAsset.class), any(ListOptions.class), any(Sort.class)))
                .thenReturn(Flux.fromArray(assets));
    }

    private void stubAgents(AiAgent... agents) {
        when(client.listAll(eq(AiAgent.class), any(ListOptions.class), any(Sort.class)))
                .thenReturn(Flux.fromArray(agents));
    }

    private static AiMemoryAsset.Spec createSpec() {
        var spec = new AiMemoryAsset.Spec();
        spec.setDisplayName("记忆块");
        spec.setTeam("team-a");
        spec.setSourceUserId("user-1");
        spec.setSourceAgentId("agent-a");
        return spec;
    }

    private static MemoryAssets.CreateCommand createCommand() {
        var spec = createSpec();
        return new MemoryAssets.CreateCommand(
                null,
                null,
                spec.getDisplayName(),
                null,
                spec.getTeam(),
                null,
                spec.getSourceUserId(),
                spec.getSourceAgentId(),
                null,
                null,
                null);
    }

    private static AiAgent agent(String name, String team, String owner) {
        var spec = new AiAgent.Spec();
        spec.setTeam(team);
        spec.setOwnerUserId(owner);
        spec.setStatus(AiAgent.AgentStatus.ACTIVE);
        var agent = new AiAgent();
        agent.setSpec(spec);
        var metadata = new Metadata();
        metadata.setName(name);
        agent.setMetadata(metadata);
        return agent;
    }

    private static AiMemoryAsset asset(
            String name,
            String team,
            String sourceUser,
            String sourceAgent,
            String owner,
            AiMemoryAsset.Visibility visibility) {
        var spec = new AiMemoryAsset.Spec();
        spec.setDisplayName(name);
        spec.setTeam(team);
        spec.setOwnerUserId(owner);
        spec.setSourceUserId(sourceUser);
        spec.setSourceAgentId(sourceAgent);
        spec.setVisibility(visibility);
        spec.setStatus(AiMemoryAsset.Status.ACTIVE);
        var asset = new AiMemoryAsset();
        asset.setSpec(spec);
        var metadata = new Metadata();
        metadata.setName(name);
        metadata.setCreationTimestamp(NOW);
        asset.setMetadata(metadata);
        return asset;
    }
}