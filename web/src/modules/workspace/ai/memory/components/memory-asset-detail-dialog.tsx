import { RefreshCw } from "lucide-react";

import { DetailDialog } from "@/components/detail-dialog";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Skeleton } from "@/components/ui/skeleton";
import { useAgentLabels } from "@/modules/workspace/ai/library/lib/agents";
import { formatUserDateTime } from "@/modules/workspace/console/users/lib/format";

import { resolveMemoryApiError } from "../lib/api";
import { MEMORY_LAYER_META, MEMORY_VISIBILITY_LABELS, memoryAssetTitle } from "../lib/model";
import { useMemoryAssetDetail } from "../lib/queries";
import { MemoryDetailRow } from "./memory-detail-row";
import { MemoryErrorState } from "./memory-states";

type MemoryAssetDetailDialogProps = {
  assetName: string;
  team: string;
  onClose: () => void;
};

export function MemoryAssetDetailDialog({
  assetName,
  team,
  onClose,
}: MemoryAssetDetailDialogProps) {
  const query = useMemoryAssetDetail(assetName, team, true);
  const agentLabels = useAgentLabels();
  const asset = query.data;

  return (
    <DetailDialog
      open
      onOpenChange={(open) => {
        if (!open) {
          onClose();
        }
      }}
      title={asset ? memoryAssetTitle(asset) : "记忆资产详情"}
      description="读取资产作用域、可见性与 L0–L3 计数，仅所有者可执行删除。"
      size="xl"
      footer={
        <>
          <Button
            type="button"
            variant="outline"
            size="sm"
            disabled={query.isFetching}
            onClick={() => void query.refetch()}
          >
            <RefreshCw className={query.isFetching ? "animate-spin" : ""} />
            刷新
          </Button>
          <Button type="button" size="sm" onClick={onClose}>
            关闭
          </Button>
        </>
      }
    >
      {query.isLoading ? (
        <div className="space-y-2">
          {Array.from({ length: 6 }, (_, index) => (
            <Skeleton key={index} className="h-5 w-full" />
          ))}
        </div>
      ) : query.isError ? (
        <MemoryErrorState
          message={resolveMemoryApiError(query.error)}
          onRetry={() => void query.refetch()}
        />
      ) : asset ? (
        <div className="space-y-4">
          <div className="grid gap-2 text-xs sm:grid-cols-2">
            <MemoryDetailRow label="资源名称">
              <span className="font-mono">{asset.name}</span>
            </MemoryDetailRow>
            <MemoryDetailRow label="状态">
              <Badge variant={asset.status === "ACTIVE" ? "secondary" : "outline"}>
                {asset.status === "ACTIVE" ? "启用" : "已停用"}
              </Badge>
            </MemoryDetailRow>
            <MemoryDetailRow label="可见性">
              {MEMORY_VISIBILITY_LABELS[asset.visibility]}
            </MemoryDetailRow>
            <MemoryDetailRow label="自动生成">{asset.autoGenerated ? "是" : "否"}</MemoryDetailRow>
            <MemoryDetailRow label="所有者">{asset.ownerUserId}</MemoryDetailRow>
            <MemoryDetailRow label="来源用户">{asset.sourceUserId}</MemoryDetailRow>
            <MemoryDetailRow label="来源 Agent">
              {asset.sourceAgentId
                ? (agentLabels.get(asset.sourceAgentId) ?? asset.sourceAgentId)
                : "—"}
            </MemoryDetailRow>
            <MemoryDetailRow label="创建者">{asset.createdByUserId ?? "—"}</MemoryDetailRow>
            <MemoryDetailRow label="创建时间">
              {formatUserDateTime(asset.createdAt ?? undefined)}
            </MemoryDetailRow>
            <MemoryDetailRow label="更新时间">
              {formatUserDateTime(asset.updatedAt ?? undefined)}
            </MemoryDetailRow>
          </div>
          {asset.description ? (
            <div className="space-y-1">
              <span className="text-xs text-muted-foreground">描述</span>
              <p className="text-sm leading-relaxed">{asset.description}</p>
            </div>
          ) : null}
          <div className="border">
            <div className="border-b px-3 py-2 text-xs text-muted-foreground">分层计数</div>
            <div className="grid grid-cols-4 divide-x">
              {MEMORY_LAYER_META.map((layer) => (
                <div key={layer.id} className="space-y-0.5 px-3 py-2">
                  <p className="text-[11px] text-muted-foreground">{layer.label}</p>
                  <p className="text-sm font-medium tabular-nums">
                    {asset.counts?.[layer.id] ?? 0}
                  </p>
                </div>
              ))}
            </div>
          </div>
          <div className="space-y-1.5">
            <span className="text-xs text-muted-foreground">绑定 Agent</span>
            {asset.agents.length > 0 ? (
              <div className="flex flex-wrap gap-1.5">
                {asset.agents.map((agent) => (
                  <Badge key={agent} variant="outline">
                    {agentLabels.get(agent) ?? agent}
                  </Badge>
                ))}
              </div>
            ) : (
              <p className="text-xs text-muted-foreground">未绑定任何 Agent。</p>
            )}
          </div>
        </div>
      ) : null}
    </DetailDialog>
  );
}
