import { Ellipsis, Eye, EyeOff, RefreshCw, Trash2 } from "lucide-react";

import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu";
import { useAgentLabels } from "@/modules/workspace/ai/library/lib/agents";
import { formatUserDateTime } from "@/modules/workspace/console/users/lib/format";

import type { MemoryAssetView, MemoryLayerCounts } from "../lib/api";
import { MEMORY_VISIBILITY_LABELS, memoryAssetTimestamp, memoryAssetTitle } from "../lib/model";
import { MemoryLayerContent } from "./memory-layer-content";
import { MemoryEmptyState } from "./memory-states";

type MemoryDetailPanelProps = {
  asset?: MemoryAssetView;
  team: string;
  counts?: MemoryLayerCounts;
  currentUserId?: string;
  refreshing: boolean;
  onRefresh: () => void;
  onToggleVisibility: () => void;
  onClear: () => void;
};

export function MemoryDetailPanel({
  asset,
  team,
  counts,
  currentUserId,
  refreshing,
  onRefresh,
  onToggleVisibility,
  onClear,
}: MemoryDetailPanelProps) {
  const agentLabels = useAgentLabels();

  if (!asset) {
    return (
      <div className="flex h-full items-center justify-center rounded-xl border bg-card">
        <MemoryEmptyState
          title="选择一个记忆块"
          description="从左侧选择记忆块，查看 L0–L3 分层内容与绑定关系。"
        />
      </div>
    );
  }

  const isOwner = Boolean(currentUserId) && asset.ownerUserId === currentUserId;
  const sourceAgent = asset.sourceAgentId
    ? (agentLabels.get(asset.sourceAgentId) ?? asset.sourceAgentId)
    : "—";

  return (
    <div className="flex h-full min-h-0 flex-col rounded-xl border bg-card">
      <div className="shrink-0 space-y-2 border-b px-4 py-3">
        <div className="flex items-start justify-between gap-3">
          <div className="min-w-0 space-y-1">
            <div className="flex flex-wrap items-center gap-1.5">
              <h2 className="truncate text-base font-medium">{memoryAssetTitle(asset)}</h2>
              <Badge variant="outline">{MEMORY_VISIBILITY_LABELS[asset.visibility]}</Badge>
              {asset.autoGenerated ? <Badge variant="secondary">自动生成</Badge> : null}
              {asset.status === "DISABLED" ? <Badge variant="outline">已停用</Badge> : null}
            </div>
            <p className="truncate font-mono text-[11px] text-muted-foreground">{asset.name}</p>
          </div>
          <div className="flex shrink-0 items-center gap-1">
            <Button
              type="button"
              variant="ghost"
              size="icon-sm"
              aria-label="刷新记忆详情"
              disabled={refreshing}
              onClick={onRefresh}
            >
              <RefreshCw className={refreshing ? "animate-spin" : ""} />
            </Button>
            {isOwner ? (
              <DropdownMenu>
                <DropdownMenuTrigger asChild>
                  <Button type="button" variant="ghost" size="icon-sm" aria-label="记忆资产操作">
                    <Ellipsis />
                  </Button>
                </DropdownMenuTrigger>
                <DropdownMenuContent align="end" className="w-40">
                  <DropdownMenuItem onSelect={onToggleVisibility}>
                    {asset.visibility === "TEAM" ? <EyeOff /> : <Eye />}
                    {asset.visibility === "TEAM" ? "切换为仅自己" : "切换为团队可见"}
                  </DropdownMenuItem>
                  <DropdownMenuSeparator />
                  <DropdownMenuItem variant="destructive" onSelect={onClear}>
                    <Trash2 />
                    清空记忆
                  </DropdownMenuItem>
                </DropdownMenuContent>
              </DropdownMenu>
            ) : null}
          </div>
        </div>
        <div className="flex flex-wrap items-center gap-x-3 gap-y-1 text-[11px] text-muted-foreground">
          <span>所有者 {asset.ownerUserId}</span>
          <span>来源 Agent {sourceAgent}</span>
          {asset.sourceUserId ? <span>来源用户 {asset.sourceUserId}</span> : null}
          {asset.createdByUserId ? <span>创建者 {asset.createdByUserId}</span> : null}
          <span>更新于 {formatUserDateTime(memoryAssetTimestamp(asset))}</span>
        </div>
        {asset.description ? (
          <p className="text-xs text-muted-foreground">{asset.description}</p>
        ) : null}
        <div className="flex flex-wrap items-center gap-1.5">
          <span className="text-[11px] text-muted-foreground">绑定 Agent</span>
          {asset.agents.length > 0 ? (
            asset.agents.map((agent) => (
              <Badge key={agent} variant="outline">
                {agentLabels.get(agent) ?? agent}
              </Badge>
            ))
          ) : (
            <span className="text-[11px] text-muted-foreground">未绑定</span>
          )}
        </div>
      </div>
      <div className="min-h-0 flex-1">
        <MemoryLayerContent
          key={asset.name}
          asset={asset}
          team={team}
          counts={counts}
          isOwner={isOwner}
        />
      </div>
    </div>
  );
}
