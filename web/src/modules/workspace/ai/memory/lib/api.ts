export async function fetchMemoryProfile(
  name: string,
  team: string,
): Promise<MemoryL3Content | null> {
  const response = await axiosInstance.get<unknown>(
    `${AI_API_PREFIX}/${MEMORY_ASSETS}/${encodeURIComponent(name)}/layers/L3`,
    { params: { limit: 1, team } },
  );
  const record = asRecord(response.data);
  if (!record) {
    return null;
  }
  const direct = readString(record.content);
  if (direct !== undefined) {
    return {
      id: toNumber(record.id),
      content: direct,
      updatedAt: readString(record.updatedAt) ?? "",
    };
  }
  const items = Array.isArray(record.items) ? record.items : [];
  const first = asRecord(items[0]);
  const content = readString(first?.content);
  if (content === undefined) {
    return null;
  }
  return {
    id: toNumber(first?.id),
    content,
    updatedAt: readString(first?.updatedAt) ?? "",
  };
}

export async function createMemoryAsset(input: MemoryAssetCreateInput): Promise<string> {
  const response = await axiosInstance.post<unknown>(`${AI_API_PREFIX}/${MEMORY_ASSETS}`, {
    apiVersion: AI_API_VERSION,
    kind: MEMORY_ASSET_KIND,
    metadata: { generateName: resourceGenerateName(input.displayName, "mem") },
    spec: {
      displayName: input.displayName,
      description: input.description,
      team: input.team,
      ownerUserId: input.ownerUserId,
      sourceUserId: input.sourceUserId,
      sourceAgentId: input.sourceAgentId,
      visibility: input.visibility,
      status: "ACTIVE",
      autoGenerated: false,
    },
  });
  const record = asRecord(response.data);
  const metadata = asRecord(record?.metadata);
  const name =
    readString(record?.name) ??
    readString(metadata?.name) ??
    readString(asRecord(record?.spec)?.name) ??
    "";
  if (!name) {
    throw new Error("创建成功但返回结果缺少资产名称。");
  }
  return name;
}

