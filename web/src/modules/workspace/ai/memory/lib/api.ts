export function resolveMemoryApiError(error: unknown): string {
  if (isAxiosError<{ code?: string; detail?: string; errors?: string[] }>(error)) {
    const code = error.response?.data?.code;
    if (code && MEMORY_ERROR_MESSAGES[code]) {
      return MEMORY_ERROR_MESSAGES[code];
    }
    const firstError = error.response?.data?.errors?.find((item) => item.trim());
    if (firstError) {
      return firstError;
    }
    if (error.response?.status === 403) {
      return MEMORY_ERROR_MESSAGES["ai-memory-asset-forbidden"];
    }
    if (error.response?.status === 409) {
      return error.response.data.detail || "操作与现有状态冲突，请刷新后重试。";
    }
  }
  return resolveApiErrorWithDetail(error, {
    notFound: "记忆资产不存在或已被删除。",
    conflict: "操作与现有状态冲突，请刷新后重试。",
  });
}
