type RecordValue = Record<string, unknown>;

function asRecord(value: unknown): RecordValue | null {
  return typeof value === "object" && value !== null && !Array.isArray(value)
    ? (value as RecordValue)
    : null;
}

function toNumber(value: unknown): number {
  if (typeof value === "number" && Number.isFinite(value)) {
    return value;
  }
  if (typeof value === "string" && value.trim()) {
    const parsed = Number(value);
    return Number.isFinite(parsed) ? parsed : 0;
  }
  return 0;
}

function readCursor(value: unknown): MemoryCursor | null {
  return typeof value === "string" || typeof value === "number" ? value : null;
}

function readString(value: unknown): string | undefined {
  return typeof value === "string" ? value : undefined;
}

function normalizeCounts(value: unknown): MemoryLayerCounts {
  const record = asRecord(value);
  return {
    L0: toNumber(record?.L0 ?? record?.l0),
    L1: toNumber(record?.["L1"] ?? record?.l1),
    L2: toNumber(record?.["L2"] ?? record?.l2),
    L3: toNumber(record?.["L3"] ?? record?.l3),
  };
}

function nextCursorFromItems<T>(items: T[], limit?: number): MemoryCursor | null {
  if (!limit || items.length < limit) {
    return null;
  }
  const last = asRecord(items[items.length - 1]);
  return readCursor(last?.id);
}

function normalizeLayerPage<T>(value: unknown, limit?: number): MemoryLayerPage<T> {
  if (Array.isArray(value)) {
    return { items: value as T[], nextCursor: nextCursorFromItems(value, limit) };
  }
  const record = asRecord(value);
  if (!record) {
    return { items: [] };
  }
  const items = Array.isArray(record.items)
    ? (record.items as T[])
    : asRecord(record.item)
      ? [record.item as T]
      : [];
  return {
    items,
    total: typeof record.total === "number" ? record.total : undefined,
    nextCursor:
      readCursor(record.nextCursor) ??
      readCursor(record.cursor) ??
      nextCursorFromItems(items, limit),
  };
}

function normalizeAsset(value: unknown): MemoryAssetView {
  const record = asRecord(value);
  return {
    ...(record as unknown as MemoryAssetView),
    counts: normalizeCounts(record?.counts),
  };
}

function normalizeAssets(value: unknown[]): MemoryAssetView[] {
  return value.map(normalizeAsset);
}

function normalizeList<T>(value: unknown): T[] {
  return Array.isArray(value) ? (value as T[]) : [];
}

export async function fetchMemoryAssets(
  query: MemoryAssetListQuery,
): Promise<{ items: MemoryAssetView[]; total: number }> {
  const response = await axiosInstance.get<unknown>(`${AI_API_PREFIX}/${MEMORY_ASSETS}`, {
    params: { limit: 200, ...query },
  });
  if (Array.isArray(response.data)) {
    return { items: normalizeAssets(response.data), total: response.data.length };
  }
  const record = asRecord(response.data);
  const items = normalizeAssets(Array.isArray(record?.items) ? record.items : []);
  return {
    items,
    total: typeof record?.total === "number" ? record.total : items.length,
  };
}

